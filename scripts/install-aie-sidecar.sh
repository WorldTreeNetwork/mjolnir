#!/bin/bash
# Install mjolnir-aie on the Linux host. Does NOT restart Elixir.
#
# Usage (on the Mjolnir host, as root):
#   sudo bash scripts/install-aie-sidecar.sh
#
# Binds 10.200.0.1:7422 on dummy-mjolnir. Never 0.0.0.0, never lo.
# User mjolnir-aie is not root and is not given operator.sock.

set -euo pipefail

ROOT="${MJOLNIR_CODE:-/opt/mjolnir}"
NATIVE="$ROOT/native"
BIN_DIR="$ROOT/bin"
BIN_DST="$BIN_DIR/mjolnir-aie"
UNIT_DST="/etc/systemd/system/mjolnir-aie.service"
ENV_DST="/etc/mjolnir/aie.env"
CATALOG_DST="/etc/mjolnir/aie-catalog.json"
HOST_IP="${MJOLNIR_HOST_API_IP:-10.200.0.1}"
PORT="${MJOLNIR_AIE_COMPUTE_PORT:-7422}"
VM_SUBNET="${MJOLNIR_VM_SUBNET:-10.192.0.0/10}"
ADMIT_SOCK="${MJOLNIR_AIE_ADMIT_SOCKET:-/run/mjolnir/aie-admit.sock}"
DEVICE="${AIE_DEVICE:-/dev/accel/accel0}"

if [[ $EUID -ne 0 ]]; then
    echo "Error: run as root" >&2
    exit 1
fi

if [[ "$HOST_IP" == "0.0.0.0" || "$HOST_IP" == "127.0.0.1" || "$HOST_IP" == "::1" ]]; then
    echo "Error: refusing bind $HOST_IP (never 0.0.0.0 or loopback)" >&2
    exit 1
fi

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
bash "$HERE/ensure-host-api-addr.sh" --install-unit

if ! ip addr show dummy-mjolnir 2>/dev/null | grep -q "inet ${HOST_IP}/32"; then
    echo "Error: ${HOST_IP}/32 is not on dummy-mjolnir; refusing to bind" >&2
    exit 1
fi

ensure_user() {
    if ! getent group mjolnir-aie >/dev/null; then
        groupadd --system mjolnir-aie
    fi
    if ! id mjolnir-aie >/dev/null 2>&1; then
        nologin="/usr/sbin/nologin"
        if [[ ! -x "$nologin" ]]; then
            nologin="/usr/bin/nologin"
        fi
        useradd --system --no-create-home --shell "$nologin" \
            --gid mjolnir-aie --comment "Mjolnir AIE sidecar" mjolnir-aie
    fi
    if getent group render >/dev/null; then
        usermod -aG render mjolnir-aie
    fi
}

ensure_accel_access() {
    if [[ -e "$DEVICE" ]]; then
        if [[ "$(stat -c %G "$DEVICE" 2>/dev/null || true)" == "root" ]]; then
            chgrp mjolnir-aie "$DEVICE" 2>/dev/null || true
            chmod 0660 "$DEVICE" 2>/dev/null || true
        fi
    fi
    if [[ -d /etc/udev/rules.d ]]; then
        cat > /etc/udev/rules.d/90-mjolnir-aie.rules << 'RULE'
KERNEL=="accel*", GROUP="mjolnir-aie", MODE="0660"
RULE
    fi
}

ensure_occupancy_acl() {
    local iron_uid runtime occ
    iron_uid="${AIE_IRON_UID:-}"
    if [[ -z "$iron_uid" ]]; then
        if [[ -d /run/user/1000/ironlab ]]; then
            iron_uid=1000
        elif [[ -d /run/user/1000 ]]; then
            iron_uid=1000
        fi
    fi
    if [[ -z "$iron_uid" ]]; then
        echo "No IRON XDG_RUNTIME_DIR; occupancy dir will follow sidecar XDG" >&2
        return 0
    fi
    runtime="/run/user/${iron_uid}"
    occ="${runtime}/ironlab"
    mkdir -p "$occ"
    if command -v setfacl >/dev/null; then
        setfacl -m "u:mjolnir-aie:--x" "$runtime" || true
        setfacl -m "u:mjolnir-aie:rwx" "$occ" || true
    else
        echo "Warning: setfacl missing; sidecar may not share occupancy.lock" >&2
    fi
    echo "AIE_OCCUPANCY_DIR=${occ}"
}

echo "=== Building mjolnir-aie ==="
if [[ -n "${MJOLNIR_CARGO:-}" ]]; then
    CARGO="$MJOLNIR_CARGO"
else
    export PATH="${HOME}/.cargo/bin:/root/.cargo/bin:${PATH}"
    if [[ "${1:-}" != "--install-only" ]] && ! command -v cargo >/dev/null; then
        echo "Error: cargo not on PATH (looked in ~/.cargo/bin)" >&2
        exit 1
    fi
    CARGO=cargo
fi
cd "$NATIVE"
if [[ "${1:-}" != "--install-only" ]]; then
    "$CARGO" build -p mjolnir-aie-sidecar --release --locked
fi
install -d "$BIN_DIR"
install -m 0755 "$NATIVE/target/release/mjolnir-aie" "$BIN_DST"
if [[ ! -s "$BIN_DST" ]]; then
    echo "Error: aie sidecar install did not leave a binary at $BIN_DST; not stopping" >&2
    exit 1
fi
install -m 0644 "$ROOT/systemd/mjolnir-aie.service" "$UNIT_DST"

ensure_user
ensure_accel_access
OCC_LINE="$(ensure_occupancy_acl)"

install -d -m 0755 /etc/mjolnir
if [[ ! -f "$ENV_DST" ]]; then
    umask 077
    cat > "$ENV_DST" << ENV
# generated by scripts/install-aie-sidecar.sh — never copy into a guest
AIE_BIND=${HOST_IP}:${PORT}
AIE_ADMIT_SOCKET=${ADMIT_SOCK}
AIE_DEVICE=${DEVICE}
AIE_CATALOG=${CATALOG_DST}
AIE_REQUIRE_ACCEL=1
${OCC_LINE}
ENV
    chmod 0640 "$ENV_DST"
    chown root:mjolnir-aie "$ENV_DST"
fi

if [[ ! -f "$CATALOG_DST" ]]; then
    cat > "$CATALOG_DST" << 'CAT'
{
  "designs": ["vector-add", "validate", "npu2-vector-add"]
}
CAT
    chmod 0644 "$CATALOG_DST"
fi

echo "=== INPUT allow TAP → ${HOST_IP}:${PORT} ==="
if command -v ufw >/dev/null && ufw status 2>/dev/null | grep -qi '^Status: active'; then
    if ! ufw status | grep -q "${HOST_IP} ${PORT}"; then
        ufw allow proto tcp from "$VM_SUBNET" to "$HOST_IP" port "$PORT" comment 'VMs to AIE sidecar'
    fi
else
    if ! iptables -C INPUT -p tcp -s "$VM_SUBNET" -d "$HOST_IP" --dport "$PORT" -j ACCEPT 2>/dev/null; then
        iptables -A INPUT -p tcp -s "$VM_SUBNET" -d "$HOST_IP" --dport "$PORT" -j ACCEPT
    fi
fi

echo "=== systemd (Elixir untouched) ==="
if [[ ! -s "$BIN_DST" ]]; then
    echo "Error: not restarting mjolnir-aie; $BIN_DST is missing" >&2
    exit 1
fi
systemctl daemon-reload
if [[ -e "$DEVICE" ]]; then
    systemctl enable mjolnir-aie
    systemctl restart mjolnir-aie
    sleep 1
    curl -fsS "http://${HOST_IP}:${PORT}/health" || true
    echo
    ss -lntp | grep "${PORT}" || true
else
    systemctl disable --now mjolnir-aie 2>/dev/null || true
    echo "No ${DEVICE}; unit installed but not started (locator omitted)"
fi
echo "=== aie sidecar installed ==="
